"""Подготовка чужого текста к отправке в чат"""


def plain_error(text) -> str:
    """Текст исключения без точки в конце

    Сообщения бота точкой не заканчиваются, а исключения приходят из аудиослоя
    и из yt-dlp со своей пунктуацией. Многоточие не трогаем
    """
    s = str(text).rstrip()
    if s.endswith('.') and not s.endswith('..'):
        return s[:-1]
    return s
